Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition @'
using System;
using System.Drawing;
using System.Drawing.Drawing2D;
using System.Globalization;
using System.IO;
using System.Text;

public static class ClockDialGenerator {
    const float Radius = 108.0f;
    const float Pi = 3.14159265358979323846f;
    static string Float(float value) {
        string text = value.ToString("R", CultureInfo.InvariantCulture);
        if (text.IndexOf('.') < 0 && text.IndexOf('E') < 0) text += ".0";
        return text + "f";
    }
    static string Point(PointF point) {
        return "{ " + Float(point.X) + ", " + Float(point.Y) + " }";
    }
    static PointF At(float angle, float radius) {
        return new PointF((float)Math.Sin(angle) * radius, -(float)Math.Cos(angle) * radius);
    }
    static void Path(StringBuilder output, string name, GraphicsPath path) {
        PathData data = path.PathData;
        output.AppendLine("const Gdiplus::PointF " + name + "Points[] = {");
        foreach (PointF point in data.Points) output.AppendLine("    " + Point(point) + ",");
        output.AppendLine("};");
        output.AppendLine("const BYTE " + name + "Types[] = { " + String.Join(", ", data.Types) + " };");
        output.AppendLine("const Path " + name + " = { " + name + "Points, " + name + "Types, " + data.Points.Length + " };");
    }
    public static void Generate(string destination) {
        var output = new StringBuilder();
        output.AppendLine("#pragma once");
        output.AppendLine("// Generated by prepare-clock-dial.ps1; no installed font is needed at runtime.");
        output.AppendLine("namespace ClockDialData {");
        output.AppendLine("constexpr float Radius = " + Float(Radius) + ";");
        output.AppendLine("struct Path { const Gdiplus::PointF* points; const BYTE* types; INT count; };");
        using (var clip = new GraphicsPath()) {
            clip.AddEllipse(-Radius, -Radius, Radius * 2, Radius * 2);
            Path(output, "Clip", clip);
        }
        using (var family = new FontFamily("Segoe UI"))
        using (var format = new StringFormat()) {
            format.Alignment = StringAlignment.Center;
            format.LineAlignment = StringAlignment.Center;
            for (int number = 1; number <= 12; ++number) {
                using (var path = new GraphicsPath()) {
                    path.AddString(number.ToString(CultureInfo.InvariantCulture), family,
                        (int)FontStyle.Regular, 16, At(number * Pi / 6, Radius - 14), format);
                    Path(output, "Number" + number, path);
                }
            }
        }
        output.AppendLine("const Path Numbers[] = {");
        for (int number = 1; number <= 12; ++number) output.AppendLine("    Number" + number + ",");
        output.AppendLine("};");
        output.AppendLine("struct Tick { Gdiplus::PointF start, end; };");
        output.AppendLine("const Tick Ticks[] = {");
        for (int tick = 0; tick < 60; ++tick) {
            float angle = tick * Pi / 30;
            output.AppendLine("    { " + Point(At(angle, Radius - (tick % 5 == 0 ? 14 : 7))) +
                ", " + Point(At(angle, Radius)) + " },");
        }
        output.AppendLine("};");
        output.AppendLine("}");
        File.WriteAllText(destination, output.ToString(), new UTF8Encoding(false));
    }
}
'@
[ClockDialGenerator]::Generate([IO.Path]::GetFullPath($OutputPath))
Write-Host "Generated: $OutputPath"
